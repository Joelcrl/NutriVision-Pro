def get_nutrition_needs(age, gender):
    """Mengambil kebutuhan nutrisi dari childNutrition_Requirements berdasarkan usia (tahun) dan jenis kelamin."""
    
    gender_key = gender.lower()
    if 'laki-laki' in gender_key:
        final_gender_key = 'male'
    elif 'perempuan' in gender_key:
        final_gender_key = 'female'
    else:
        return None

    if final_gender_key not in childNutrition_Requirements:
        return None

    needs = childNutrition_Requirements[final_gender_key]
    
    for age_range, nutrition_data in needs.items():
        min_age, max_age = age_range
        if min_age <= age <= max_age:
            return nutrition_data
    
    return None